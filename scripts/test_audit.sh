#!/usr/bin/env bash
# Self-test of the registry audit (wiki/methodology/registry-and-audit.md).
#
# Runs `lake exe audit_fixture <case>` on the fixtures in test/AuditFixtures.
# The case `good` must pass. Each other case plants one fault and must fail
# with the expected message.
#
# The case `bad_axiom` needs a theorem that uses a new axiom. The repository must
# not contain one (scripts/check_forbidden.py), so this script writes the module
# to test/AuditFixtures/Generated/ (git-ignored), builds it, and deletes it on exit.
#
# Usage: scripts/test_audit.sh   (from any directory)
set -euo pipefail

cd "$(dirname "$0")/.."
export PATH="$HOME/.elan/bin:$PATH"

gen_dir=test/AuditFixtures/Generated
cleanup() { rm -rf "$gen_dir"; }
trap cleanup EXIT

mkdir -p "$gen_dir"
cat > "$gen_dir/BadAxiom.lean" <<'EOF'
import AuditFixtures.Props
-- Generated by scripts/test_audit.sh. Planted fault: a new axiom.
namespace AuditFixtures.Generated.BadAxiom
axiom cheat : AuditFixtures.Props.addZero
theorem cheat_proven : AuditFixtures.Props.addZero := cheat
end AuditFixtures.Generated.BadAxiom
EOF

lake build audit_fixture +AuditFixtures.Generated.BadAxiom

fails=0

expect_pass() {
  local name=$1 out
  if out=$(lake exe audit_fixture "$name" 2>&1); then
    echo "ok   $name (passed as expected)"
  else
    echo "FAIL $name: expected pass, got:"; echo "$out"; fails=$((fails + 1))
  fi
}

expect_fail() {
  local name=$1 msg=$2 out
  if out=$(lake exe audit_fixture "$name" 2>&1); then
    echo "FAIL $name: expected the audit to reject it, but it passed:"; echo "$out"
    fails=$((fails + 1))
  elif ! grep -qF -- "$msg" <<<"$out"; then
    echo "FAIL $name: rejected, but without the message '$msg':"; echo "$out"
    fails=$((fails + 1))
  else
    echo "ok   $name (rejected: $msg)"
  fi
}

expect_pass good
expect_fail wrong_type        "expected exactly \`AuditFixtures.Props.addZero\`"
expect_fail unfolded          "expected exactly \`AuditFixtures.Props.addZero\`"
expect_fail not_negated       "expected exactly \`Not AuditFixtures.Props.addComm\`"
expect_fail negated_as_proven "expected exactly \`AuditFixtures.Props.subAddCancel\`"
expect_fail bad_axiom         "uses forbidden axioms [AuditFixtures.Generated.BadAxiom.cheat]"
expect_fail missing_thm       "theorem \`AuditFixtures.Proofs.noSuchTheorem\` does not exist"
expect_fail open_with_thm     "status open, but theorem"
expect_fail missing_bug       "refuted, but no bug record is given"
expect_fail missing_bug_file  "bug record \`bugs/no-such-file.yaml\` does not exist"
expect_fail missing_row       "inventory row \`core.Fx.noSuchRow\` does not exist"
expect_fail unnamed_modelled  "inventory row core.Fx.unnamed: status modelled, but no registry entry is named"
expect_fail duplicate_id      "duplicate entry id fx.addZero"

if [ "$fails" -ne 0 ]; then
  echo "FAIL: $fails audit self-test case(s) failed."
  exit 1
fi
echo "OK: all audit self-test cases behaved as expected."
